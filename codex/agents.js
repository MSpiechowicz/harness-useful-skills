import { readFile } from "node:fs/promises";
import path from "node:path";

/** First line of every Codex agent file; the installer recognises its own files by it. */
export const AGENT_MARKER = "# Generated by Useful Skills for Codex; edits are replaced on reinstall.";
/** The role file stems, in dispatch order; each file defines the agent type `us-<role>`. */
export const AGENT_ROLES = Object.freeze(["planner", "scout", "frontend", "backend", "general-purpose", "reviewer", "security-reviewer"]);

const OPEN = "developer_instructions = '''\n";
const CLOSE = "\n'''\n";

function basicString(value, key) {
  // The generated files only use plain double-quoted strings; JSON escapes are a subset of TOML's.
  if (!/^"(?:[^"\\\u0000-\u001f]|\\["\\])*"$/.test(value)) throw new Error(`Invalid ${key} string`);
  return JSON.parse(value);
}

/**
 * Parses the restricted shape the agent files use:
 *   marker line, `name = "..."`, `description = "..."`, then `developer_instructions` as a '''-literal string.
 * Anything else throws. Returns `{ name, description, developer_instructions }`.
 */
export function parseAgentToml(text) {
  const lines = text.split("\n");
  if (lines[0] !== AGENT_MARKER) throw new Error("Missing the Useful Skills marker on the first line");
  const fields = {};
  for (const key of ["name", "description"]) {
    const line = lines[Object.keys(fields).length + 1] ?? "";
    const prefix = `${key} = `;
    if (!line.startsWith(prefix)) throw new Error(`Expected ${key} on line ${Object.keys(fields).length + 2}`);
    fields[key] = basicString(line.slice(prefix.length), key);
  }
  const rest = `${lines.slice(3).join("\n")}`;
  if (!rest.startsWith(OPEN) || !rest.endsWith(CLOSE)) throw new Error("developer_instructions must be a ''' literal string that ends the file");
  const body = rest.slice(OPEN.length, rest.length - CLOSE.length + 1);
  if (body.includes("'''")) throw new Error("developer_instructions must not contain '''");
  if (body.trim() === "") throw new Error("developer_instructions is empty");
  return { ...fields, developer_instructions: body };
}

/** Reads and validates every role file in `directory`. Resolves to `[{ role, file, text, agent }]` in role order. */
export async function readAgents(directory) {
  return Promise.all(AGENT_ROLES.map(async role => {
    const file = path.join(directory, `${role}.toml`);
    const text = await readFile(file, "utf8");
    const agent = parseAgentToml(text);
    if (agent.name !== `us-${role}`) throw new Error(`${file}: name must be us-${role}`);
    return { role, file, text, agent };
  }));
}
