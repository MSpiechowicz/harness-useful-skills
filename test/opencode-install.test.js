test("the status report describes a healthy, a modified and a missing install", (t) => {
  const box = setup(t);
  const status = () => inspectOpenCodeInstall({ scope: "user", cwd: box.cwd, environment: box.environment }).text;
  assert.match(status(), /not installed/);

  box.install();
  const healthy = status();
  assert.match(healthy, /Useful Skills 1\.0\.0/);
  assert.match(healthy, /0 modified, 0 missing/);
  assert.match(healthy, /Agents: 7 of 7/);
  assert.match(healthy, /has mcp\.harness-useful-skills, as installed/);
  assert.match(healthy, /present, mode 700/);

  writeFileSync(box.at("commands", "useful-skills.md"), "edited\n");
  writeFileSync(box.at("opencode.json"), JSON.stringify({ mcp: { "harness-useful-skills": { type: "remote" } } }));
  const damaged = status();
  assert.match(damaged, /1 modified/);
  assert.match(damaged, /different mcp\.harness-useful-skills/);
});

