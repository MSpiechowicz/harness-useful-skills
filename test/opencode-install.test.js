import assert from "node:assert/strict";
import { existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, statSync, symlinkSync, writeFileSync } from "node:fs";
import path from "node:path";
import test from "node:test";

import { installOpenCode } from "../opencode/install.js";
import { inspectOpenCodeInstall } from "../opencode/install-status.js";
import { createInstallSandbox, writeBundle } from "./helpers/opencode-install-fixture.js";

const AGENTS = ["backend", "frontend", "general-purpose", "planner", "reviewer", "scout", "security-reviewer"];

function setup(t, bundleOptions) {
  const box = createInstallSandbox();
  t.after(box.cleanup);
  writeBundle(box.bundleRoot, bundleOptions);
  const install = (options = {}) => installOpenCode({ scope: "user", cwd: box.cwd, environment: box.environment, bundleRoot: box.bundleRoot, ...options });
  return { ...box, install, at: (...parts) => path.join(box.configDir, ...parts), readJson: (file) => JSON.parse(readFileSync(file, "utf8")) };
}

/** Every file and directory under `directory`, relative and sorted, for before/after comparisons. */
function listTree(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { recursive: true }).sort();
}

test("a fresh user install lays out the plugin, skills, commands, agents, record and config", (t) => {
  const box = setup(t);
  const result = box.install();

  assert.equal(result.actionRequired, false);
  assert.match(result.message, /Restart OpenCode/);
  assert.ok(existsSync(box.at("plugins", "harness-useful-skills.js")));
  assert.ok(existsSync(box.at("plugins", "harness-useful-skills", "opencode", "v1.js")));
  assert.ok(existsSync(box.at("plugins", "harness-useful-skills", "opencode", "agents", "scout.md")));
  assert.ok(existsSync(box.at("skills", "us-plan", "SKILL.md")));
  assert.ok(existsSync(box.at("skills", "us-plan", "references", "brief.md")));
  assert.ok(existsSync(box.at("commands", "useful-skills.md")));
  assert.ok(existsSync(box.at("commands", "us-ignore-workflow.md")));
  assert.equal(existsSync(box.at("plugins", "package.json")), false, "a package.json directly in plugins/ would redirect every plugin");

  for (const agent of AGENTS) {
    assert.match(readFileSync(box.at("agents", `us-${agent}.md`), "utf8"), /\n# Generated by Useful Skills /);
  }
  assert.ok(existsSync(box.at("harness-useful-skills", "models.yml")));
  assert.equal(statSync(box.dataDir).mode & 0o777, 0o700);

  const record = box.readJson(box.at("plugins", "harness-useful-skills", "install-record.json"));
  assert.equal(record.schema, 1);
  assert.equal(record.version, "1.0.0");
  assert.equal(record.scope, "user");
  assert.equal(record.scopeRoot, box.configDir);
  assert.equal(record.dataDir, box.dataDir);
  assert.equal(record.configFile, box.at("opencode.json"));
  assert.ok(record.files["plugins/harness-useful-skills.js"]);
  assert.ok(record.files["skills/us-plan/SKILL.md"]);
  assert.ok(record.files["commands/useful-skills.md"]);
  assert.equal(Object.keys(record.files).some((rel) => rel.startsWith("agents/")), false, "generated agents are marker-owned, not hashed");

  const config = box.readJson(box.at("opencode.json"));
  assert.deepEqual(config.mcp["harness-useful-skills"], record.mcpEntry);
  assert.deepEqual(config.mcp["harness-useful-skills"].command, ["node", box.at("plugins", "harness-useful-skills", "opencode", "mcp-server.js")]);
  assert.equal(config.mcp["harness-useful-skills"].enabled, true);
  assert.equal(config.mcp["harness-useful-skills"].timeout, 600000);
});

test("installing again changes nothing", (t) => {
  const box = setup(t);
  box.install();
  const watched = [box.at("plugins", "harness-useful-skills", "install-record.json"), box.at("opencode.json"), box.at("skills", "us-plan", "SKILL.md"), box.at("agents", "us-scout.md"), box.at("harness-useful-skills", "models.yml")];
  const before = watched.map((file) => ({ ino: lstatSync(file).ino, mtime: lstatSync(file).mtimeMs }));
  const tree = listTree(box.configDir);

  const result = box.install();

  assert.match(result.message, /already installed/);
  assert.equal(result.actionRequired, false);
  assert.deepEqual(watched.map((file) => ({ ino: lstatSync(file).ino, mtime: lstatSync(file).mtimeMs })), before);
  assert.deepEqual(listTree(box.configDir), tree);
});

test("an upgrade replaces changed files and removes stale owned ones", (t) => {
  const box = setup(t, { files: { "opencode/old.js": "old\n", "opencode/skills/us-old/SKILL.md": "old skill\n" } });
  box.install();
  assert.ok(existsSync(box.at("plugins", "harness-useful-skills", "opencode", "old.js")));

  writeBundle(box.bundleRoot, { version: "2.0.0", files: { "opencode/old.js": null, "opencode/skills/us-old/SKILL.md": null } });
  const result = box.install();

  assert.match(result.message, /2\.0\.0/);
  assert.equal(existsSync(box.at("plugins", "harness-useful-skills", "opencode", "old.js")), false);
  assert.equal(existsSync(box.at("skills", "us-old")), false, "directories emptied by the removal go too");
  assert.match(readFileSync(box.at("skills", "us-plan", "SKILL.md"), "utf8"), /Plan 2\.0\.0/);
  const record = box.readJson(box.at("plugins", "harness-useful-skills", "install-record.json"));
  assert.equal(record.version, "2.0.0");
  assert.equal(record.files["plugins/harness-useful-skills/opencode/old.js"], undefined);
});

test("a stale file the user edited is left in place and reported", (t) => {
  const box = setup(t, { files: { "opencode/old.js": "old\n" } });
  box.install();
  writeFileSync(box.at("plugins", "harness-useful-skills", "opencode", "old.js"), "mine\n");

  writeBundle(box.bundleRoot, { version: "2.0.0", files: { "opencode/old.js": null } });
  const result = box.install();

  assert.equal(readFileSync(box.at("plugins", "harness-useful-skills", "opencode", "old.js"), "utf8"), "mine\n");
  assert.match(result.message, /old\.js/);
  assert.equal(box.readJson(box.at("plugins", "harness-useful-skills", "install-record.json")).files["plugins/harness-useful-skills/opencode/old.js"], undefined);
});

test("an existing file Useful Skills did not install blocks the install before anything is written", (t) => {
  const box = setup(t);
  mkdirSync(box.at("skills", "us-plan"), { recursive: true });
  writeFileSync(box.at("skills", "us-plan", "SKILL.md"), "my own skill\n");
  const tree = listTree(box.configDir);

  assert.throws(() => box.install(), /SKILL\.md.*did not install/s);

  assert.equal(readFileSync(box.at("skills", "us-plan", "SKILL.md"), "utf8"), "my own skill\n");
  assert.deepEqual(listTree(box.configDir), tree);
  assert.equal(existsSync(box.dataDir), false);
});

test("a user-modified installed file blocks an upgrade before anything is written", (t) => {
  const box = setup(t);
  box.install();
  writeFileSync(box.at("commands", "useful-skills.md"), "edited\n");
  writeBundle(box.bundleRoot, { version: "2.0.0" });
  const tree = listTree(box.configDir);

  assert.throws(() => box.install(), /useful-skills\.md.*modified/s);

  assert.equal(readFileSync(box.at("commands", "useful-skills.md"), "utf8"), "edited\n");
  assert.match(readFileSync(box.at("skills", "us-plan", "SKILL.md"), "utf8"), /Plan 1\.0\.0/);
  assert.deepEqual(listTree(box.configDir), tree);
});

test("a symlinked target directory blocks the install and writes nothing", (t) => {
  const box = setup(t);
  const elsewhere = path.join(box.root, "elsewhere");
  mkdirSync(elsewhere);
  mkdirSync(box.configDir, { recursive: true });
  symlinkSync(elsewhere, box.at("skills"));

  assert.throws(() => box.install(), /symbolic link/);

  assert.deepEqual(readdirSync(elsewhere), []);
  assert.deepEqual(listTree(box.configDir), ["skills"]);
});

test("symlinked plugins, agents or models directories block the install too", (t) => {
  for (const blocked of [["plugins"], ["agents"], ["harness-useful-skills"]]) {
    const box = setup(t);
    const elsewhere = path.join(box.root, "elsewhere");
    mkdirSync(elsewhere);
    mkdirSync(box.configDir, { recursive: true });
    symlinkSync(elsewhere, box.at(...blocked));

    assert.throws(() => box.install(), /symbolic link/, blocked.join("/"));
    assert.deepEqual(readdirSync(elsewhere), [], blocked.join("/"));
  }
});

