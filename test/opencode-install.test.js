test("a crafted install record cannot inject terminal escapes into the status report", (t) => {
  const box = setup(t);
  box.install();
  const recordFile = box.at("plugins", "harness-useful-skills", "install-record.json");
  const record = box.readJson(recordFile);
  const status = () => inspectOpenCodeInstall({ scope: "user", cwd: box.cwd, environment: box.environment }).text;

  writeFileSync(recordFile, JSON.stringify({ ...record, version: "1.0.0\u001b]0;owned\u0007" }));
  assert.match(status(), /cannot be used \(The OpenCode install record has an unexpected format\.\)/);

  writeFileSync(recordFile, JSON.stringify({ ...record, dataDir: `${record.dataDir}\u001b[2J` }));
  assert.doesNotMatch(status(), /[\u0000-\u0009\u000b-\u001f\u007f-\u009f]/);
});

test("an install into a path with control characters is refused before anything is created", (t) => {
  const box = setup(t);
  const cwd = path.join(box.root, "evil\u001b[2Jdir");
  mkdirSync(cwd);

  assert.throws(() => box.install({ scope: "project", cwd }), /control characters/);
  assert.deepEqual(readdirSync(cwd), []);

  const environment = { ...box.environment, XDG_CONFIG_HOME: path.join(box.root, "evil\u009bconfig") };
  assert.throws(() => box.install({ environment }), /control characters/);
  assert.equal(existsSync(environment.XDG_CONFIG_HOME), false);
});

test("the status report prints paths without control characters", (t) => {
  const box = setup(t);
  const environment = { ...box.environment, XDG_CONFIG_HOME: path.join(box.root, "evil\u001b[2Jconfig") };
  mkdirSync(path.join(environment.XDG_CONFIG_HOME, "opencode"), { recursive: true });

  const { text } = inspectOpenCodeInstall({ scope: "user", cwd: box.cwd, environment });

  assert.match(text, /not installed \(no install record in .*evil \[2Jconfig/);
  assert.doesNotMatch(text, /[\u0000-\u0009\u000b-\u001f\u007f-\u009f]/);
});
