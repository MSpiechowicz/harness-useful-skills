test("a project install goes under .opencode, edits its config and warns about machine-specific paths", (t) => {
  const box = setup(t);
  const result = box.install({ scope: "project" });
  const root = path.join(box.cwd, ".opencode");

  assert.ok(existsSync(path.join(root, "plugins", "harness-useful-skills.js")));
  assert.ok(existsSync(path.join(root, "agents", "us-planner.md")));
  assert.deepEqual(box.readJson(path.join(root, "opencode.json")).mcp["harness-useful-skills"].command, ["node", path.join(root, "plugins", "harness-useful-skills", "opencode", "mcp-server.js")]);
  assert.match(result.message, /machine/);
  assert.match(result.message, /\.gitignore/);
  assert.deepEqual(listTree(box.configDir), ["harness-useful-skills"], "a project install leaves the user config alone except for the settings directory");
  assert.equal(box.readJson(path.join(root, "plugins", "harness-useful-skills", "install-record.json")).scope, "project");
});

