import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";

import { claudeLegacyNotes, pluginDataName, resolveHostContext } from "../claude/host-context.js";
import { generatedAgentName, modelsConfigPath, syncRoleAgents } from "../claude/models.js";
import { LEGACY_CLAUDE_PLUGIN_ID, LEGACY_DATA_DIRECTORY, legacyClaudeAgentFile } from "../legacy-names.js";
import { workspaceMemoryPaths } from "../memory-paths.js";
import { readWorkflowSnapshot, writeWorkflowSetting } from "../workflow-settings.js";
import { fixture } from "./helpers/claude-doctor-fixture.js";

const PLUGIN_ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");

function configDirectory(t) {
  const directory = mkdtempSync(path.join(os.tmpdir(), "us-claude-migration-"));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  return directory;
}

/** What the plugin under its earlier name had written into a Claude config dir: models, a saved setting, generated agents. */
function writeEarlierState(configDir) {
  const legacy = path.join(configDir, LEGACY_DATA_DIRECTORY);
  mkdirSync(path.join(legacy, "workflow-settings"), { recursive: true, mode: 0o700 });
  writeFileSync(path.join(legacy, "models.yml"), "modelRoles:\n  default: claude-haiku-5-5:low\n");
  writeFileSync(path.join(legacy, "workflow-settings", "plan.json"), "false\n", { mode: 0o600 });

  mkdirSync(path.join(configDir, "agents"), { recursive: true });
  for (const agent of ["planner", "scout"]) {
    writeFileSync(path.join(configDir, "agents", legacyClaudeAgentFile(agent)), `---\n# Generated by Useful Skills from /old/models.yml (role: x). Edit that file instead; this file is overwritten.\nname: ${generatedAgentName(agent)}\n---\nold body\n`);
  }
  return legacy;
}

test("the first session moves the models file and saved settings from the earlier folder and keeps the user's model choices", t => {
  const configDir = configDirectory(t);
  const legacy = writeEarlierState(configDir);

  const result = syncRoleAgents({ configDir, pluginRoot: PLUGIN_ROOT });

  assert.equal(result.created, false, "the edited models file is not replaced by defaults");
  assert.equal(existsSync(legacy), false);
  assert.equal(readFileSync(modelsConfigPath(configDir), "utf8"), "modelRoles:\n  default: claude-haiku-5-5:low\n");
  assert.equal(readFileSync(path.join(configDir, "harness-useful-skills", "workflow-settings", "plan.json"), "utf8"), "false\n");
  assert.equal(result.agents.planner.selection.model, "claude-haiku-5-5");
});

test("saved settings are read from the new folder after the move", async t => {
  const configDir = configDirectory(t);
  writeEarlierState(configDir);

  const snapshot = await readWorkflowSnapshot({ configDir, cwd: configDir });

  assert.equal(snapshot.values.plan, false);
  assert.equal(snapshot.sources.plan, "file");
  assert.equal(existsSync(path.join(configDir, LEGACY_DATA_DIRECTORY)), false);
});

test("a setting written after the rename lands in the new folder only", async t => {
  const configDir = configDirectory(t);
  writeEarlierState(configDir);

  await writeWorkflowSetting({ agentDir: configDir, cwd: configDir, key: "review", enabled: false });

  assert.deepEqual((await readdir(path.join(configDir, "harness-useful-skills", "workflow-settings"))).sort(), ["plan.json", "review.json"]);
  assert.equal(existsSync(path.join(configDir, LEGACY_DATA_DIRECTORY)), false);
});

test("generated role agents under the earlier file names are replaced, the user's own file with that name is not", t => {
  const configDir = configDirectory(t);
  writeEarlierState(configDir);
  writeFileSync(path.join(configDir, "agents", legacyClaudeAgentFile("scout")), "---\nname: mine\n---\nuser written\n");

  syncRoleAgents({ configDir, pluginRoot: PLUGIN_ROOT });

  const files = readdirSync(path.join(configDir, "agents")).sort();
  assert.equal(files.includes(legacyClaudeAgentFile("planner")), false, "the generated earlier agent is gone");
  assert.equal(files.includes(legacyClaudeAgentFile("scout")), true, "a file Harness Skills did not generate stays");
  assert.equal(readFileSync(path.join(configDir, "agents", legacyClaudeAgentFile("scout")), "utf8"), "---\nname: mine\n---\nuser written\n");
  assert.equal(files.filter(file => file.startsWith("harness-useful-skills-")).length, 8);
});

test("an invalid models file leaves the earlier generated agents in place", t => {
  const configDir = configDirectory(t);
  writeEarlierState(configDir);
  writeFileSync(path.join(configDir, LEGACY_DATA_DIRECTORY, "models.yml"), "not: valid\n");

  const result = syncRoleAgents({ configDir, pluginRoot: PLUGIN_ROOT });

  assert.ok(result.error);
  assert.equal(existsSync(path.join(configDir, "agents", legacyClaudeAgentFile("planner"))), true);
});

test("a models file edited in both folders keeps the new one and leaves the old one for the user", t => {
  const configDir = configDirectory(t);
  const legacy = writeEarlierState(configDir);
  mkdirSync(path.join(configDir, "harness-useful-skills"), { recursive: true, mode: 0o700 });
  writeFileSync(modelsConfigPath(configDir), "modelRoles:\n  default: claude-opus-5-5:high\n");

  syncRoleAgents({ configDir, pluginRoot: PLUGIN_ROOT });

  assert.equal(readFileSync(modelsConfigPath(configDir), "utf8"), "modelRoles:\n  default: claude-opus-5-5:high\n");
  assert.equal(readFileSync(path.join(legacy, "models.yml"), "utf8"), "modelRoles:\n  default: claude-haiku-5-5:low\n");
  assert.match(claudeLegacyNotes({ CLAUDE_CONFIG_DIR: configDir }).join("\n"), /still holds files that were not moved/);
});

test("the renamed plugin's memory is carried over from the data folder of the plugin under its earlier id", async t => {
  const f = await fixture(t);
  const earlier = path.join(path.dirname(f.dataDir), pluginDataName(LEGACY_CLAUDE_PLUGIN_ID));
  const memory = path.join(earlier, LEGACY_DATA_DIRECTORY, "memory", "hash", "claude-facts");
  await mkdir(memory, { recursive: true, mode: 0o700 });
  await writeFile(path.join(memory, "00000.json"), JSON.stringify({ content: "remembered" }), { mode: 0o600 });
  await mkdir(path.join(earlier, LEGACY_DATA_DIRECTORY, "dependencies", "lock", "venv"), { recursive: true });

  await resolveHostContext({ workspace: f.repo, data: f.dataDir });

  const moved = path.join(f.dataDir, "harness-useful-skills", "memory", "hash", "claude-facts", "00000.json");
  assert.equal(await readFile(moved, "utf8"), JSON.stringify({ content: "remembered" }));
  assert.equal(existsSync(path.join(earlier, LEGACY_DATA_DIRECTORY)), false);
  assert.equal(existsSync(path.join(f.dataDir, "harness-useful-skills", "dependencies")), false, "the environment cache is rebuilt, not moved");
});

test("the memory path is the new folder, and a project's saved facts are found there", async t => {
  const f = await fixture(t);
  const paths = await workspaceMemoryPaths({ cwd: f.repo, agentDir: f.dataDir });

  assert.ok(paths.directory.startsWith(path.join(f.dataDir, "harness-useful-skills", "memory")));
});

test("doctor lists the earlier plugin while it is still installed", async t => {
  const f = await fixture(t);
  await mkdir(path.join(f.configDir, "plugins"), { recursive: true });
  await writeFile(path.join(f.configDir, "plugins", "installed_plugins.json"), JSON.stringify({ version: 2, plugins: { [LEGACY_CLAUDE_PLUGIN_ID]: [{ scope: "user" }] } }));

  const report = await f.run(["doctor", "--check"]);

  assert.match(report.text, /\nLeftover from an earlier install\n {2}The earlier plugin useful-skills@useful-skills-local is still installed\. Remove it with `claude plugin uninstall useful-skills@useful-skills-local`/);
});

test("doctor reports nothing extra when no earlier install is left", async t => {
  const f = await fixture(t);

  const report = await f.run(["doctor", "--check"]);

  assert.doesNotMatch(report.text, /Leftover from an earlier install/);
});
