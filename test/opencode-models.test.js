import assert from "node:assert/strict";
import { mkdir, mkdtemp, readdir, readFile, realpath, rm, stat, symlink, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";

import { ROLE_AGENTS } from "../model-roles.js";
import { generatedAgentPath, modelsConfigPath, openCodeRoutingContext, parseOpenCodeSelector, syncOpenCodeAgents } from "../opencode/models.js";

const AGENTS = Object.keys(ROLE_AGENTS);

async function scopeRoot(t) {
  const root = await realpath(await mkdtemp(path.join(os.tmpdir(), "us-opencode-models-")));
  t.after(() => rm(root, { recursive: true, force: true }));
  return path.join(root, "opencode");
}

/** The frontmatter lines of a generated agent file. */
function frontmatter(text) {
  const match = /^---\n([\s\S]*?)\n---\n/.exec(text);
  assert.ok(match, "generated agent has a closed frontmatter block");
  return match[1].split("\n");
}

test("selectors take a provider/model and only a known variant suffix", () => {
  assert.deepEqual(parseOpenCodeSelector("review", "anthropic/claude-sonnet-4-5:high"), { model: "anthropic/claude-sonnet-4-5", variant: "high" });
  assert.deepEqual(parseOpenCodeSelector("review", "ollama/llama3:8b"), { model: "ollama/llama3:8b", variant: undefined });
  assert.deepEqual(parseOpenCodeSelector("review", "ollama/llama3:8b:max"), { model: "ollama/llama3:8b", variant: "max" });
  assert.deepEqual(parseOpenCodeSelector("review", "openrouter/anthropic/claude-opus-4:none"), { model: "openrouter/anthropic/claude-opus-4", variant: "none" });
  assert.deepEqual(parseOpenCodeSelector("review", "inherit"), { model: null, variant: undefined });

  for (const raw of ["claude-sonnet", "/model", "anthropic/", "Anthropic/model", "anthropic/model:", "anthropic/mo\"del", "anthropic/model;rm", "anthropic/:high"]) {
    assert.throws(() => parseOpenCodeSelector("review", raw), /Invalid selector for role "review"/, raw);
  }
});

test("first sync writes a role-less models file and inherit-model agents from the templates", async t => {
  const root = await scopeRoot(t);
  const result = syncOpenCodeAgents({ scopeRoot: root });

  assert.equal(result.created, true);
  assert.equal(result.configFile, modelsConfigPath(root));
  assert.equal(result.error, undefined);
  assert.match(await readFile(result.configFile, "utf8"), /^modelRoles:\n$/m);
  assert.equal((await stat(path.dirname(result.configFile))).mode & 0o777, 0o700);

  assert.deepEqual((await readdir(path.join(root, "agents"))).sort(), AGENTS.map(agent => `us-${agent}.md`).sort());
  for (const agent of AGENTS) {
    const text = await readFile(generatedAgentPath(root, agent), "utf8");
    const lines = frontmatter(text);
    assert.match(lines[0], /^# Generated by Useful Skills /);
    assert.ok(lines.includes("mode: subagent"));
    assert.ok(!lines.some(line => /^(model|variant):/.test(line)), `${agent} inherits the session model`);
    assert.equal(result.agents[agent].state, "created");
  }

  const scout = frontmatter(await readFile(generatedAgentPath(root, "scout"), "utf8"));
  assert.ok(scout.includes("permission:") && scout.includes("  \"*\": deny") && scout.includes("  grep: allow"), "template permissions are kept");
});

test("configured roles set a quoted model and variant, and unchanged agents are left alone", async t => {
  const root = await scopeRoot(t);
  syncOpenCodeAgents({ scopeRoot: root });
  await writeFile(modelsConfigPath(root), "modelRoles:\n  default: anthropic/claude-sonnet-4-5\n  review: \"openai/gpt-5:high\"\n  research: inherit\n");

  const result = syncOpenCodeAgents({ scopeRoot: root });
  assert.equal(result.agents.reviewer.state, "updated");
  assert.equal(result.agents.scout.state, "ready", "research inherits, as before");

  const reviewer = frontmatter(await readFile(generatedAgentPath(root, "reviewer"), "utf8"));
  assert.ok(reviewer.includes("model: \"openai/gpt-5\""));
  assert.ok(reviewer.includes("variant: high"));
  const backend = frontmatter(await readFile(generatedAgentPath(root, "backend"), "utf8"));
  assert.ok(backend.includes("model: \"anthropic/claude-sonnet-4-5\""));
  assert.ok(!backend.some(line => line.startsWith("variant:")));

  const again = syncOpenCodeAgents({ scopeRoot: root });
  assert.ok(Object.values(again.agents).every(agent => agent.state === "ready"));

  const context = openCodeRoutingContext(again);
  assert.match(context, /`us-reviewer`: openai\/gpt-5, variant high/);
  assert.match(context, /`us-scout`: inherits the session model/);
});

test("a user-owned agent file is never overwritten and an invalid config changes nothing", async t => {
  const root = await scopeRoot(t);
  const own = generatedAgentPath(root, "planner");
  await mkdir(path.dirname(own), { recursive: true });
  await writeFile(own, "---\ndescription: mine\n---\nMine.\n");

  const result = syncOpenCodeAgents({ scopeRoot: root });
  assert.equal(result.agents.planner.state, "conflict");
  assert.equal(await readFile(own, "utf8"), "---\ndescription: mine\n---\nMine.\n");
  assert.match(openCodeRoutingContext(result), /`us-planner`: .* was not generated by Useful Skills/);

  const backend = await readFile(generatedAgentPath(root, "backend"), "utf8");
  await writeFile(modelsConfigPath(root), "modelRoles:\n  backend: not-a-selector\n");
  const invalid = syncOpenCodeAgents({ scopeRoot: root });
  assert.match(invalid.error, /Invalid selector for role "backend"/);
  assert.deepEqual(invalid.agents, {});
  assert.equal(await readFile(generatedAgentPath(root, "backend"), "utf8"), backend);
  assert.match(openCodeRoutingContext(invalid), /is invalid/);
});

test("the sync refuses to write through a symlinked agents or models directory", async t => {
  for (const linked of ["agents", "useful-skills"]) {
    const root = await scopeRoot(t);
    const outside = path.join(path.dirname(root), "outside");
    await mkdir(outside);
    await mkdir(root);
    await symlink(outside, path.join(root, linked));

    const result = syncOpenCodeAgents({ scopeRoot: root });

    assert.match(result.blocked, /symbolic link/, linked);
    assert.deepEqual(result.agents, {}, linked);
    assert.deepEqual(await readdir(outside), [], `${linked} target stays empty`);
    assert.match(openCodeRoutingContext(result), /not generated or updated: .*symbolic link/, linked);
  }
});

test("the sync refuses a symlinked agent file, a symlinked models file and a non-directory component", async t => {
  const root = await scopeRoot(t);
  const outside = path.join(path.dirname(root), "outside.md");
  await writeFile(outside, "precious\n");
  await mkdir(path.join(root, "agents"), { recursive: true });
  await symlink(outside, generatedAgentPath(root, "scout"));
  assert.match(syncOpenCodeAgents({ scopeRoot: root }).blocked, /us-scout\.md is a symbolic link/);
  assert.equal(await readFile(outside, "utf8"), "precious\n");
  assert.deepEqual((await readdir(path.join(root, "agents"))).sort(), ["us-scout.md"]);

  const other = await scopeRoot(t);
  await mkdir(other, { recursive: true });
  await writeFile(path.join(other, "agents"), "a file, not a directory\n");
  assert.match(syncOpenCodeAgents({ scopeRoot: other }).blocked, /not a directory/);
});
